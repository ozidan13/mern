#!/usr/bin/env node
/* ============================================================
   scripts/build-search-index.mjs — scans pages → data/search-index.js
   ------------------------------------------------------------
   Contract:
   - Zero dependencies (Node 22+ standard library only).
   - Extracts title, track, kind, headings, body text, code snippets.
   - Arabic text normalization (alef variants, ta-marbuta, harakat).
   - Emits compact window.FSA.searchIndex to data/search-index.js.
   ============================================================ */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');
const outputFile = path.join(rootDir, 'data', 'search-index.js');

function normalizeArabic(text) {
  if (!text) return '';
  return text
    .replace(/[\u064B-\u065F\u0670]/g, '') // strip tashkeel / harakat
    .replace(/[أإآ]/g, 'ا')                 // normalize alef
    .replace(/ة/g, 'ه')                    // normalize ta marbuta
    .replace(/ى/g, 'ي')                    // normalize ya
    .toLowerCase();
}

function stripTags(html) {
  if (!html) return '';
  return html.replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim();
}

function extractMeta(html, name) {
  const m = html.match(new RegExp(`<meta\\s+name=["']fsa-${name}["']\\s+content=["'](.*?)["']`, 'i'));
  return m ? m[1] : '';
}

function processHtmlFile(filePath, relUrl) {
  const content = fs.readFileSync(filePath, 'utf-8');

  const titleMatch = content.match(/<title>(.*?)<\/title>/i);
  const h1Match = content.match(/<h1[^>]*>(.*?)<\/h1>/i);
  const title = extractMeta(content, 'title') || (h1Match ? stripTags(h1Match[1]) : '') || (titleMatch ? stripTags(titleMatch[1]).split('·')[0].trim() : path.basename(filePath, '.html'));

  const track = extractMeta(content, 'track') || (relUrl.startsWith('learn/') ? relUrl.split('/')[1] : '');
  const lesson = extractMeta(content, 'lesson') || path.basename(filePath, '.html');
  const level = extractMeta(content, 'level') || '1';

  // Determine kind
  let kind = 'lesson';
  if (relUrl.startsWith('reference/')) kind = 'reference';
  else if (relUrl.startsWith('projects/')) kind = 'project';
  else if (relUrl.startsWith('exercises/')) kind = 'exercise';

  // Extract headings
  const headings = [];
  const headingMatches = content.matchAll(/<h[2-4][^>]*>(.*?)<\/h[2-4]>/gi);
  for (const h of headingMatches) {
    headings.push(stripTags(h[1]));
  }

  // Extract body prose
  const pMatches = content.match(/<p[^>]*>([\s\S]*?)<\/p>/gi) || [];
  const bodyText = pMatches.map(p => stripTags(p)).join(' ').slice(0, 1500);

  // Extract code terms
  const codeMatches = content.match(/<code>([\s\S]*?)<\/code>/gi) || [];
  const codeKeywords = Array.from(new Set(codeMatches.map(c => stripTags(c).replace(/[^\w\.\-\$]/g, '')).filter(w => w.length > 2))).slice(0, 30).join(' ');

  return {
    t: title,
    url: relUrl,
    track: track,
    kind: kind,
    level: level,
    h: headings.join(' · '),
    body: bodyText,
    code: codeKeywords,
    norm: normalizeArabic(`${title} ${headings.join(' ')} ${bodyText}`)
  };
}

function buildSearchIndex() {
  const records = [];
  const searchDirs = ['learn', 'reference', 'projects', 'exercises'];

  for (const dir of searchDirs) {
    const fullDir = path.join(rootDir, dir);
    if (!fs.existsSync(fullDir)) continue;

    function walk(current) {
      const files = fs.readdirSync(current, { withFileTypes: true });
      for (const file of files) {
        const fullPath = path.join(current, file.name);
        if (file.isDirectory()) {
          walk(fullPath);
        } else if (file.name.endsWith('.html') && file.name !== 'index.html') {
          const relUrl = path.relative(rootDir, fullPath).replace(/\\/g, '/');
          records.push(processHtmlFile(fullPath, relUrl));
        }
      }
    }

    walk(fullDir);
  }

  const outputCode = `/* ============================================================
   data/search-index.js — Client-Side Search Index
   ------------------------------------------------------------
   Auto-generated by scripts/build-search-index.mjs.
   ============================================================ */
(function () {
  'use strict';

  window.FSA = window.FSA || {};
  window.FSA.searchIndex = ${JSON.stringify(records, null, 2)};
})();
`;

  fs.writeFileSync(outputFile, outputCode, 'utf-8');
  console.log(`✅ Successfully generated data/search-index.js (${records.length} documents indexed)`);
}

buildSearchIndex();
